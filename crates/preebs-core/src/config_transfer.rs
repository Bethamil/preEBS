use serde_json::Value;

use crate::error::{Error, Result};
use crate::model::{
    ConfigExportDocument, HourType, Project, Task, UserConfig, CONFIG_EXPORT_TYPE,
    CONFIG_EXPORT_VERSION, DEFAULT_USER_ID,
};
use crate::normalize::{normalize_config, normalize_max_from_raw};
use crate::text::{now_iso, safe_trim};

/// Parsed `preebs-config` v1 payload, before `normalizeConfig` clamping.
#[derive(Debug, Clone, PartialEq)]
pub struct ParsedConfig {
    pub max_hours_per_day: Vec<f64>,
    pub default_hour_type_name: Option<String>,
    pub projects: Vec<Project>,
}

pub fn build_config_export(config: &UserConfig) -> ConfigExportDocument {
    ConfigExportDocument {
        doc_type: CONFIG_EXPORT_TYPE.to_string(),
        version: CONFIG_EXPORT_VERSION,
        exported_at: now_iso(),
        config: config.clone(),
    }
}

/// Same acceptance rules as `parseConfigImportPayload` in `lib/config-transfer.ts`.
pub fn parse_config_import(payload: &Value) -> Result<ParsedConfig> {
    let Some(object) = payload.as_object() else {
        return Err(invalid_config());
    };
    if object.get("type").and_then(Value::as_str) != Some(CONFIG_EXPORT_TYPE) {
        return Err(invalid_config());
    }
    if object.get("version").and_then(Value::as_u64) != Some(CONFIG_EXPORT_VERSION) {
        return Err(invalid_config());
    }
    let Some(raw_config) = object.get("config").and_then(Value::as_object) else {
        return Err(invalid_config());
    };
    let default_hour_type_name = raw_config
        .get("defaultHourTypeName")
        .and_then(Value::as_str)
        .map(safe_trim)
        .filter(|name| !name.is_empty());
    Ok(ParsedConfig {
        max_hours_per_day: parse_max_hours(raw_config.get("maxHoursPerDay")),
        default_hour_type_name,
        projects: parse_projects(raw_config.get("projects")),
    })
}

pub fn parsed_to_config(parsed: ParsedConfig) -> UserConfig {
    let mut config = UserConfig {
        user_id: DEFAULT_USER_ID.to_string(),
        max_hours_per_day: normalize_max_from_raw(&parsed.max_hours_per_day),
        default_hour_type_name: parsed
            .default_hour_type_name
            .unwrap_or_else(crate::model::default_hour_type_name),
        projects: parsed.projects,
        updated_at: now_iso(),
    };
    config = normalize_config(config);
    config
}

fn invalid_config() -> Error {
    Error::validation("Invalid config file. Use a file generated by Config Export.")
}

fn parse_max_hours(value: Option<&Value>) -> Vec<f64> {
    let Some(items) = value.and_then(Value::as_array) else {
        return Vec::new();
    };
    items.iter().filter_map(js_number).collect()
}

fn js_number(value: &Value) -> Option<f64> {
    match value {
        Value::Number(number) => number.as_f64().filter(|number| number.is_finite()),
        Value::String(text) => {
            let parsed: f64 = text.trim().parse().ok()?;
            parsed.is_finite().then_some(parsed)
        }
        Value::Bool(true) => Some(1.0),
        Value::Bool(false) | Value::Null => Some(0.0),
        Value::Array(_) | Value::Object(_) => None,
    }
}

fn parse_projects(value: Option<&Value>) -> Vec<Project> {
    let Some(items) = value.and_then(Value::as_array) else {
        return Vec::new();
    };
    items.iter().filter_map(parse_project).collect()
}

fn parse_project(value: &Value) -> Option<Project> {
    let object = value.as_object()?;
    let name = safe_trim(object.get("name").and_then(Value::as_str).unwrap_or(""));
    if name.is_empty() {
        return None;
    }
    let label = safe_trim(object.get("label").and_then(Value::as_str).unwrap_or(""));
    Some(Project {
        id: safe_trim(object.get("id").and_then(Value::as_str).unwrap_or("")),
        name,
        label: if label.is_empty() { None } else { Some(label) },
        tasks: parse_tasks(object.get("tasks")),
    })
}

fn parse_tasks(value: Option<&Value>) -> Vec<Task> {
    let Some(items) = value.and_then(Value::as_array) else {
        return Vec::new();
    };
    items.iter().filter_map(parse_task).collect()
}

fn parse_task(value: &Value) -> Option<Task> {
    let object = value.as_object()?;
    let name = safe_trim(object.get("name").and_then(Value::as_str).unwrap_or(""));
    if name.is_empty() {
        return None;
    }
    Some(Task {
        id: safe_trim(object.get("id").and_then(Value::as_str).unwrap_or("")),
        name,
        hour_types: parse_hour_types(object.get("hourTypes")),
    })
}

fn parse_hour_types(value: Option<&Value>) -> Vec<HourType> {
    let Some(items) = value.and_then(Value::as_array) else {
        return Vec::new();
    };
    items.iter().filter_map(parse_hour_type).collect()
}

fn parse_hour_type(value: &Value) -> Option<HourType> {
    let object = value.as_object()?;
    let name = safe_trim(object.get("name").and_then(Value::as_str).unwrap_or(""));
    if name.is_empty() {
        return None;
    }
    Some(HourType {
        id: safe_trim(object.get("id").and_then(Value::as_str).unwrap_or("")),
        name,
    })
}
